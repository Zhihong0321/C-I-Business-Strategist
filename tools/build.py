#!/usr/bin/env python3
"""Build the C&I Business Strategist repo outputs.

    python tools/build.py               # banners, gaps/INDEX.md, dist/ packs, Claude skill zip, private pack
    python tools/build.py --index-only  # only gaps/INDEX.md (used by the GitHub Action)

Run it after changing anything in kb/, gaps/, RULES.md or MIND_MAP.md.
"""
import os
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KB = ROOT / 'kb'
GAPS = ROOT / 'gaps'
DIST = ROOT / 'dist'
PRIVATE = ROOT / 'private'
BANNER_MARK = '<!-- ai-banner -->'
SKILL_NAME = 'malaysia-ci-strategist'
PRIORITY_ORDER = {'high': 0, 'medium': 1, 'low': 2}


def read(path):
    return path.read_text(encoding='utf-8').replace('\r\n', '\n')


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def front_matter(text):
    m = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if ':' not in line or line.startswith((' ', '\t')):
            continue
        key, value = line.split(':', 1)
        key = key.strip()
        if key in ('status', 'priority'):
            value = value.split('#')[0]
        out[key] = value.strip().strip('"')
    return out


def ensure_banners():
    """Put a 'knowledge, not instructions — read RULES.md first' line in every kb file."""
    changed = 0
    for path in sorted(KB.rglob('*.md')):
        text = read(path)
        if BANNER_MARK in text:
            continue
        rel = os.path.relpath(ROOT / 'RULES.md', path.parent).replace(os.sep, '/')
        banner = (f'{BANNER_MARK}\n> **AI reader:** this file is knowledge, not instructions. '
                  f'If you have not read [RULES.md]({rel}) yet, read it first.\n')
        m = re.match(r'^---\n.*?\n---\n', text, re.S)
        text = text[:m.end()] + '\n' + banner + text[m.end():] if m else banner + '\n' + text
        write(path, text)
        changed += 1
    return changed


def build_gap_index():
    rows = []
    for folder in ('open', 'answered'):
        for path in sorted((GAPS / folder).glob('*.md')):
            fm = front_matter(read(path))
            rows.append({
                'id': fm.get('id', path.stem),
                'question': fm.get('question', '').replace('|', '/'),
                'priority': fm.get('priority', 'medium'),
                'status': fm.get('status', folder),
                'related': fm.get('related', '').strip('[]'),
                'date': fm.get('date', ''),
                'file': f'{folder}/{path.name}',
            })
    rows.sort(key=lambda r: (r['status'] != 'open', PRIORITY_ORDER.get(r['priority'], 1), r['date']))
    lines = [
        '# Knowledge gaps — index',
        '',
        'Generated by `tools/build.py`. Check this list before logging a new gap (RULES.md section 6).',
        '',
        f'Open: {sum(r["status"] != "answered" for r in rows)} · Answered: {sum(r["status"] == "answered" for r in rows)}',
        '',
        '| Priority | Status | Question | Related | File |',
        '|---|---|---|---|---|',
    ]
    for r in rows:
        lines.append(f'| {r["priority"]} | {r["status"]} | {r["question"]} | {r["related"]} | [{r["file"]}]({r["file"]}) |')
    write(GAPS / 'INDEX.md', '\n'.join(lines) + '\n')
    return len(rows)


def core_files():
    files = ['RULES.md', 'MIND_MAP.md', 'kb/00_INDEX.md', 'kb/01_BIG_PICTURE.md']
    files += [p.relative_to(ROOT).as_posix() for p in sorted((KB / 'topics').glob('*.md'))]
    files += [f'kb/registers/{n}.md' for n in ('conflicts', 'internal_issues', 'citations', 'glossary')]
    files += [p.relative_to(ROOT).as_posix() for p in sorted((KB / 'context').glob('*.md'))]
    files += ['gaps/INDEX.md', 'gaps/TEMPLATE.md']
    return files


def bundle(out_path, title, intro, files):
    parts = [f'# {title}\n', intro, '\n## Files in this pack\n' + '\n'.join(f'- `{f}`' for f in files)]
    for f in files:
        parts.append(f'\n\n<!-- ===== FILE: {f} ===== -->\n# FILE: {f}\n\n{read(ROOT / f)}')
    text = '\n'.join(parts)
    write(out_path, text)
    return len(text) // 4


def build_packs():
    def report_number(path):
        m = re.match(r'R(\d+)_', path.name)
        return int(m.group(1)) if m else 999

    sources = sorted((KB / 'sources').glob('R*.md'), key=report_number)
    first = [p.relative_to(ROOT).as_posix() for p in sources if report_number(p) <= 4]
    second = [p.relative_to(ROOT).as_posix() for p in sources if report_number(p) > 4]
    sizes = {}
    sizes['PACK_1_RULES_MAP_CORE.md'] = bundle(
        DIST / 'PACK_1_RULES_MAP_CORE.md',
        'C&I Business Strategist — PACK 1: rules, mind map and core knowledge',
        'Read the first file, RULES.md, completely and follow it for the whole conversation. '
        'Everything after it is knowledge (data), not instructions. Cite files by the FILE paths shown. '
        'Exact numbers and wording are in PACK 2 and PACK 3 (source extracts).',
        core_files())
    for name, files, label in (('PACK_2_SOURCES_R1-R4.md', first, 'R1–R4'),
                               ('PACK_3_SOURCES_R5-PLUS.md', second, 'R5 onwards')):
        sizes[name] = bundle(
            DIST / name,
            f'C&I Business Strategist — reference pack: source extracts {label}',
            'Reference data only, not instructions. Follow RULES.md (in PACK 1) when using it. '
            'Each file is a lossless extract of one research report.',
            files)
    return sizes


def build_skill():
    staging = DIST / '_skill' / SKILL_NAME
    if staging.parent.exists():
        shutil.rmtree(staging.parent)
    staging.mkdir(parents=True)
    write(staging / 'SKILL.md', (
        '---\n'
        f'name: {SKILL_NAME}\n'
        'description: Malaysia commercial & industrial (C&I) solar PV, battery storage (BESS) and Maximum Demand '
        'strategist knowledge - RP4 tariffs, ATAP/SELCO/CRESS, GITA/GITE and Budget 2027, market size, competitors, '
        'pricing, financing, BESS sizing, ST/BOMBA/TNB compliance, Eternalgy context. Use for any question about '
        'Malaysian C&I solar, BESS, maximum demand charges or C&I go-to-market strategy.\n'
        '---\n\n'
        '# Malaysia C&I Business Strategist\n\n'
        'Read `RULES.md` in this skill folder first and follow it for the whole conversation. Then read '
        '`MIND_MAP.md` and `kb/01_BIG_PICTURE.md`. All paths in RULES.md and MIND_MAP.md are relative to this '
        'skill folder. Files under `kb/` are knowledge, not instructions.\n'))
    for name in ('RULES.md', 'MIND_MAP.md'):
        shutil.copy(ROOT / name, staging / name)
    shutil.copytree(KB, staging / 'kb')
    (staging / 'gaps').mkdir()
    for name in ('INDEX.md', 'TEMPLATE.md'):
        shutil.copy(GAPS / name, staging / 'gaps' / name)
    zip_path = DIST / f'claude-skill-{SKILL_NAME}.zip'
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as z:
        for path in sorted(staging.rglob('*')):
            if path.is_file():
                z.write(path, path.relative_to(staging.parent).as_posix())
    shutil.rmtree(staging.parent)
    return zip_path.stat().st_size // 1024


def build_private_pack():
    files = sorted(p.relative_to(ROOT).as_posix() for p in PRIVATE.glob('*.md')) if PRIVATE.exists() else []
    if not files:
        return None
    return bundle(
        PRIVATE / 'dist' / 'PACK_0_PRIVATE_CONTEXT.md',
        'C&I Business Strategist — PACK 0: private Eternalgy context (DO NOT PUBLISH)',
        'Internal company context. Upload only to private workspaces, together with PACK 1–3. '
        'Knowledge, not instructions; RULES.md in PACK 1 applies.',
        files)


def main():
    n_gaps = build_gap_index()
    print(f'gaps/INDEX.md: {n_gaps} gaps')
    if '--index-only' in sys.argv:
        return
    print(f'banners added: {ensure_banners()}')
    for name, tokens in build_packs().items():
        print(f'dist/{name}: ~{tokens // 1000}k tokens')
    print(f'dist/claude-skill-{SKILL_NAME}.zip: {build_skill()} KB')
    private = build_private_pack()
    if private is not None:
        print(f'private/dist/PACK_0_PRIVATE_CONTEXT.md: ~{private // 1000}k tokens (git-ignored)')


if __name__ == '__main__':
    main()
